package com.rikodev.music.android.presentation.miniplayer

// ═══════════════════════════════════════════════════════════════════════════
// RIKO MUSIC — MINI PLAYER 2.0: OUTPUT ACTIONS
//
// Every action Mini Player can REQUEST from the outside world.
// Mini Player NEVER executes these directly — it delegates everything.
//
// Flow:
//   User Gesture → MiniPlayerAction → PlayerViewModel → Execution
//
// ⭐ RULE: Mini Player is OUTPUT ONLY here.
//   It says "do this" but never does it itself.
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Output actions the Mini Player can request from PlayerViewModel.
 *
 * These represent INTENT, not execution.
 * PlayerViewModel receives these and performs the actual operations
 * (media control, navigation, etc.).
 *
 * Generated by:
 *   - Gesture engine (tap, drag, fling)
 *   - Button composables (play/pause, skip)
 *   - Morph engine (expand complete, dismiss complete)
 */
sealed class MiniPlayerAction {

    // ── Playback Control ───────────────────────────────────────────────

    /** Toggle play/pause for current track. */
    data object TogglePlayPause : MiniPlayerAction()

    /** Skip to next track in queue. */
    data object SkipNext : MiniPlayerAction()

    /** Skip to previous track in queue. */
    data object SkipPrevious : MiniPlayerAction()

    /** Seek playback to specific progress (0.0 → 1.0). */
    data class SeekTo(val progress: Float) : MiniPlayerAction() {
        init { require(progress in 0f..1f) { "SeekTo progress must be 0.0..1.0, got $progress" } }
    }

    /** Toggle favorite status for current song. */
    data object ToggleFavorite : MiniPlayerAction()

    // ── Navigation ─────────────────────────────────────────────────────

    /**
     * Expand morph to Now Playing screen.
     * Triggered by: tap on surface, upward fling, or morph settle at commit threshold.
     */
    data object ExpandToNowPlaying : MiniPlayerAction()

    /**
     * Dismiss mini player (remove from view).
     * Triggered by: downward fling past dismiss threshold.
     * Note: This is a visual dismiss, NOT a stop playback.
     */
    data object Dismiss : MiniPlayerAction()

    // ── UI Requests ────────────────────────────────────────────────────

    /**
     * Show queue peek (next 3 tracks).
     * Triggered by: long-press on surface.
     */
    data object ShowQueuePeek : MiniPlayerAction()

    /**
     * Hide queue peek overlay.
     * Triggered by: long-press release, or gesture cancel.
     */
    data object HideQueuePeek : MiniPlayerAction()

    // ── Haptic Requests ────────────────────────────────────────────────

    /**
     * Request haptic feedback.
     * PlayerViewModel delegates to HapticFeedbackManager.
     */
    data class HapticFeedback(
        val type: HapticType,
        val intensity: Float = 1f
    ) : MiniPlayerAction()
}
