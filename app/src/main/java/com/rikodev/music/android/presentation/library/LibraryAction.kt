package com.rikodev.music.android.presentation.library

// ═══════════════════════════════════════════════════════════════════════════
// RIKO MUSIC — MILESTONE 2: LIBRARY RUNTIME — OUTPUT ACTIONS
//
// Phase A, File 4: LibraryAction.kt
//
// Every action Library can REQUEST from the outside world.
// Library NEVER executes these directly — it delegates everything.
//
// Flow:
//   User Interaction → LibraryAction → LibraryViewModel → Execution
//
// ⭐ RULE: Library is OUTPUT ONLY here.
//   It says "do this" but never does it itself.
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Output actions the Library can request from LibraryViewModel.
 *
 * These represent INTENT, not execution.
 * LibraryViewModel receives these and performs the actual operations
 * (playback, navigation, data refresh, etc.).
 *
 * Generated by:
 *   - User taps (album, song, artist, folder)
 *   - Selection mode actions
 *   - Search/filter interactions
 *   - System lifecycle triggers
 */
sealed class LibraryAction {

    // ── Playback ────────────────────────────────────────────────────────

    /**
     * Play a specific song.
     *
     * @param songId Song to play.
     * @param contextPlaylist Playlist/album providing play context. Null = single.
     */
    data class PlaySong(
        val songId: Long,
        val contextPlaylist: Long? = null
    ) : LibraryAction()

    /**
     * Toggle favorite status for a song.
     *
     * @param songId Song to toggle favorite.
     */
    data class ToggleFavorite(val songId: Long) : LibraryAction()

    // ── Navigation ──────────────────────────────────────────────────────

    /**
     * Navigate to album detail screen.
     *
     * @param albumId Album to display.
     */
    data class NavigateToAlbum(val albumId: Long) : LibraryAction()

    /**
     * Navigate to artist detail screen.
     *
     * @param artistId Artist to display.
     */
    data class NavigateToArtist(val artistId: Long) : LibraryAction()

    /**
     * Navigate to folder detail screen.
     *
     * @param folderPath Folder to display.
     */
    data class NavigateToFolder(val folderPath: String) : LibraryAction()

    /**
     * Navigate to playlist detail screen.
     *
     * @param playlistId Playlist to display.
     */
    data class NavigateToPlaylist(val playlistId: Long) : LibraryAction()

    /**
     * Navigate to smart collection detail screen.
     *
     * @param collectionId Collection to display.
     */
    data class NavigateToCollection(val collectionId: String) : LibraryAction()

    /**
     * Expand Mini Player to Now Playing.
     */
    data object ExpandMiniPlayer : LibraryAction()

    // ── Selection Actions ──────────────────────────────────────────────

    /**
     * Enter selection mode with an initial item selected.
     *
     * @param itemId First selected item.
     */
    data class EnterSelectionMode(val itemId: Long) : LibraryAction()

    /**
     * Add selected items to a playlist.
     */
    data class AddToPlaylist(val playlistId: Long) : LibraryAction()

    /**
     * Delete all selected items.
     */
    data object DeleteSelected : LibraryAction()

    /**
     * Share all selected items.
     */
    data object ShareSelected : LibraryAction()

    // ── Search ───────────────────────────────────────────────────────────

    /**
     * Open full search screen (Milestone 3).
     * Library search is just a quick filter; this opens the full experience.
     *
     * @param query Initial search query from Library search bar.
     */
    data class OpenSearch(val query: String = "") : LibraryAction()

    // ── Data ───────────────────────────────────────────────────────────

    /**
     * Request Library content refresh.
     * Triggered by pull-to-refresh or after scan completes.
     */
    data object RefreshContent : LibraryAction()

    /**
     * Request permission for media access.
     */
    data object RequestPermission : LibraryAction()

    // ── Haptic ──────────────────────────────────────────────────────────

    /**
     * Request haptic feedback.
     */
    data class HapticFeedback(
        val type: HapticType
    ) : LibraryAction()

    // ── Context Menu ──────────────────────────────────────────────────

    /**
     * Show context menu for an item.
     *
     * @param itemType Type of the item.
     * @param itemId Item unique ID.
     */
    data class ShowContextMenu(
        val itemType: ContextMenuTarget,
        val itemId: Long
    ) : LibraryAction()
}

// ─────────────────────────────────────────────────────────────────────────────
// SUPPORTING TYPES
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Haptic feedback types for Library interactions.
 */
enum class HapticType {
    /** Light tap on card/item. */
    TAP,

    /** Long press triggered. */
    LONG_PRESS,

    /** Selection toggled. */
    SELECTION_TOGGLE,

    /** Fast scroll section jumped. */
    FAST_SCROLL_JUMP
}

/**
 * Target type for context menu.
 */
enum class ContextMenuTarget {
    SONG,
    ALBUM,
    ARTIST,
    FOLDER,
    PLAYLIST
}
